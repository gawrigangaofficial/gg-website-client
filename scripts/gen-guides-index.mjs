/**
 * Builds the generated guide files in src/content/guides from the guide files in that folder:
 *   cards.js  small metadata index for lists and links (loaded on many pages)
 *   index.js  every guide with its full text (Node only: prerender and checks)
 * To add a guide: create src/content/guides/<slug>.js (see scripts/check-guides.mjs for the required shape), then run
 *   npm run guides
 * The browser loads each guide on demand (Vite glob in src/Pages/Guides/GuideSlugPage.jsx), so a guide page downloads
 * only its own text.
 */
import fs from 'node:fs'
import path from 'node:path'
import { pathToFileURL } from 'node:url'

const DIR = path.resolve('src', 'content', 'guides')
const NOT_GUIDES = ['index.js', 'topics.js', 'cards.js', 'lookup.js']
const slugs = fs
  .readdirSync(DIR)
  .filter((f) => f.endsWith('.js') && !NOT_GUIDES.includes(f))
  .map((f) => f.replace(/\.js$/, ''))
  .sort()

const { GUIDE_TOPICS, START_HERE } = await import(pathToFileURL(path.join(DIR, 'topics.js')).href)
const topicIndex = (g) => {
  const i = GUIDE_TOPICS.findIndex((t) => t.key === g.category)
  return i < 0 ? GUIDE_TOPICS.length : i
}

const loaded = []
for (const slug of slugs) {
  const g = (await import(`${pathToFileURL(path.join(DIR, `${slug}.js`)).href}?t=${Date.now()}`)).default
  if (!g) throw new Error(`${slug}.js has no default export`)
  loaded.push(g)
}
loaded.sort((a, b) => {
  const sa = START_HERE.indexOf(a.slug)
  const sb = START_HERE.indexOf(b.slug)
  if (sa !== sb) return (sa < 0 ? 99 : sa) - (sb < 0 ? 99 : sb)
  return topicIndex(a) - topicIndex(b) || a.title.localeCompare(b.title)
})

const cards = loaded.map((g) => ({
  slug: g.slug,
  title: g.title,
  excerpt: g.excerpt,
  category: g.category,
  lang: g.lang || undefined,
  readMinutes: g.readMinutes,
  heroImage: g.heroImage,
  published: g.published,
  updated: g.updated,
}))
fs.writeFileSync(
  path.join(DIR, 'cards.js'),
  `// GENERATED by scripts/gen-guides-index.mjs. Do not edit by hand: change a guide file, then run \`npm run guides\`.
export const GUIDE_CARDS = ${JSON.stringify(cards, null, 2)}
`,
)

const imports = slugs.map((s, i) => `import g${i} from './${s}.js'`).join('\n')
const list = slugs.map((_, i) => `g${i}`).join(', ')
fs.writeFileSync(
  path.join(DIR, 'index.js'),
  `// GENERATED by scripts/gen-guides-index.mjs. Do not edit by hand: add a guide file, then run \`npm run guides\`.
// Node only (prerender and checks). The browser uses ./lookup.js and loads one guide at a time.
${imports}
import { START_HERE, GUIDE_TOPICS } from './topics.js'

export { GUIDE_REDIRECTS, GUIDE_TOPICS, HINDI_KEY, START_HERE, resolveGuideSlug, guideText } from './topics.js'
export { GUIDE_CARDS, getCard, guideCard, relatedCards } from './lookup.js'

const topicIndex = (g) => {
  const i = GUIDE_TOPICS.findIndex((t) => t.key === g.category)
  return i < 0 ? GUIDE_TOPICS.length : i
}

/** Every guide with its full text: the start-here guides first, then by topic, then by title. */
export const GUIDES = [${list}].sort((a, b) => {
  const sa = START_HERE.indexOf(a.slug)
  const sb = START_HERE.indexOf(b.slug)
  if (sa !== sb) return (sa < 0 ? 99 : sa) - (sb < 0 ? 99 : sb)
  return topicIndex(a) - topicIndex(b) || a.title.localeCompare(b.title)
})

export function getGuide(slug) {
  return GUIDES.find((g) => g.slug === slug) || null
}
`,
)
console.log(`guides: ${slugs.length} (cards.js and index.js written)`)
