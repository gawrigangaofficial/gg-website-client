export const SEO_GUIDES = ALL_SEO_GUIDES.filter((guide) => !MERGED_GUIDES[guide.slug])

const CLUSTERS = [
  ['rudraksha', 'mukhi', 'washroom', 'bathing'],
  ['karungali', 'ebony'],
  ['tulsi', 'shyam', 'rama'],
  ['bracelet', 'wrist'],
  ['spray', 'aura', 'smoke'],
  ['gift', 'hamper', 'diwali', 'combo'],
]

export function getSeoGuide(slug) {
  return SEO_GUIDES.find((guide) => guide.slug === slug) || null
}

export function relatedGuideSlugs(slug, limit = 3) {
  const current = getSeoGuide(slug)
  const blob = `${current?.slug || ''} ${current?.keyword || ''}`.toLowerCase()
  const cluster = CLUSTERS.find((words) => words.some((word) => blob.includes(word))) || []
  return SEO_GUIDES
    .filter((guide) => guide.slug !== slug)
    .map((guide) => {
      const text = `${guide.slug} ${guide.keyword} ${guide.title}`.toLowerCase()
      const score = cluster.reduce((total, word) => total + (text.includes(word) ? 2 : 0), 0)
      return { slug: guide.slug, score }
    })
    .sort((a, b) => b.score - a.score)
    .slice(0, limit)
    .map((guide) => guide.slug)
}
